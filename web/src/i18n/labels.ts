export function displayLabel(value: string | null | undefined, lang: Lang): string {
  if (!value) return "—";
  return LABELS[lang][value] ?? value.replaceAll("_", " ");
}

export function connectionLabel(value: string | null | undefined, lang: Lang): string {
  const normalized = (value ?? "missing").toLowerCase();
  const key =
    normalized === "healthy" || normalized === "configured" || normalized === "online"
      ? "connected"
      : normalized === "missing" || normalized === "not_configured"
        ? "not_configured"
        : normalized === "disabled"
          ? "disabled"
          : ["authentication_failed", "unreachable", "timeout", "model_not_found", "rate_limited", "error"].includes(normalized)
            ? "connection_error"
            : "needs_check";
  const labels = {
    zh: {
      connected: "已连接",
      not_configured: "未配置",
      connection_error: "连接异常",
      disabled: "已禁用",
      needs_check: "需要检查",
    },
    en: {
      connected: "Connected",
      not_configured: "Not configured",
      connection_error: "Connection error",
      disabled: "Disabled",
      needs_check: "Needs attention",
    },
  } as const;
  return labels[lang][key];
}
